import { getZonedParts, startOfZonedDay, zonedTimeToUtc, LONDON_TZ } from '#lib/utils/time';
import type { PriceInterval, PriceSlot } from './types';

export const SLOT_MINUTES = 30;
export const SLOT_MS = SLOT_MINUTES * 60_000;

/**
 * Intelligent Octopus Go's super-low window. Published in the tariff
 * description as "23:30 - 05:30 every night" and stable across products.
 */
export const OFF_PEAK_START_MINUTES = 23 * 60 + 30; // 23:30
export const OFF_PEAK_END_MINUTES = 5 * 60 + 30; // 05:30

/** True when an instant falls inside the Intelligent Go off-peak window. */
export function isOffPeakInstant(instant: Date, timeZone: string = LONDON_TZ): boolean {
	const { hour, minute } = getZonedParts(instant, timeZone);
	const minutesIntoDay = hour * 60 + minute;
	return minutesIntoDay >= OFF_PEAK_START_MINUTES || minutesIntoDay < OFF_PEAK_END_MINUTES;
}

/** Resolve the unit rate (p/kWh inc VAT) applicable at a given instant. */
export type PriceResolver = (instant: Date) => number | null;

/** Build a resolver from a list of (possibly multi-hour) API rate intervals. */
export function priceResolverFromIntervals(intervals: readonly PriceInterval[]): PriceResolver {
	const sorted = [...intervals].sort((a, b) => a.start.getTime() - b.start.getTime());

	return (instant: Date) => {
		const t = instant.getTime();
		let low = 0;
		let high = sorted.length - 1;
		let match = -1;

		while (low <= high) {
			const mid = (low + high) >> 1;
			if (sorted[mid].start.getTime() <= t) {
				match = mid;
				low = mid + 1;
			} else {
				high = mid - 1;
			}
		}

		if (match === -1) return null;
		const interval = sorted[match];
		return t < interval.end.getTime() ? interval.priceIncVat : null;
	};
}

/** Build a resolver for two-band (day/night) tariffs. */
export function priceResolverFromBands(
	peakPriceIncVat: number,
	offPeakPriceIncVat: number,
	timeZone: string = LONDON_TZ
): PriceResolver {
	return (instant: Date) =>
		isOffPeakInstant(instant, timeZone) ? offPeakPriceIncVat : peakPriceIncVat;
}

/** The UTC instant at which the local day after `dayStart` begins. */
export function nextZonedDayStart(dayStart: Date, timeZone: string = LONDON_TZ): Date {
	const { year, month, day } = getZonedParts(dayStart, timeZone);
	const rolled = new Date(Date.UTC(year, month - 1, day + 1));
	return zonedTimeToUtc(
		{ year: rolled.getUTCFullYear(), month: rolled.getUTCMonth() + 1, day: rolled.getUTCDate() },
		timeZone
	);
}

/**
 * Build the half-hourly price slots for the local day containing `date`.
 *
 * DST-aware: a spring-forward day yields 46 slots and an autumn day 50, because
 * slots are generated by walking real instants between two local midnights.
 */
export function buildDaySlots(
	date: Date,
	resolve: PriceResolver,
	timeZone: string = LONDON_TZ
): PriceSlot[] {
	const start = startOfZonedDay(date, timeZone);
	const end = nextZonedDayStart(start, timeZone);
	const slots: PriceSlot[] = [];

	for (let t = start.getTime(); t < end.getTime(); t += SLOT_MS) {
		const slotStart = new Date(t);
		const price = resolve(slotStart);
		if (price === null) continue;
		slots.push({
			start: slotStart,
			end: new Date(Math.min(t + SLOT_MS, end.getTime())),
			priceIncVat: price,
			offPeak: isOffPeakInstant(slotStart, timeZone)
		});
	}

	return slots;
}

/** The slot covering `now`, or the closest slot when out of range. */
export function getCurrentSlot(slots: readonly PriceSlot[], now: Date): PriceSlot | null {
	if (!slots.length) return null;
	const t = now.getTime();

	const covering = slots.find((slot) => slot.start.getTime() <= t && t < slot.end.getTime());
	if (covering) return covering;

	return slots.reduce((closest, slot) =>
		Math.abs(slot.start.getTime() - t) < Math.abs(closest.start.getTime() - t) ? slot : closest
	);
}

/** Given a local wall-clock time on the day of `instant` (plus an optional day offset), return the UTC instant. */
function zonedTimeOnDay(
	instant: Date,
	hour: number,
	minute: number,
	dayOffset: number,
	timeZone: string
): Date {
	const { year, month, day } = getZonedParts(instant, timeZone);
	const rolled = new Date(Date.UTC(year, month - 1, day + dayOffset));
	return zonedTimeToUtc(
		{
			year: rolled.getUTCFullYear(),
			month: rolled.getUTCMonth() + 1,
			day: rolled.getUTCDate(),
			hour,
			minute
		},
		timeZone
	);
}

export interface OffPeakStatus {
	offPeak: boolean;
	/** When the off-peak state next flips, even across midnight. */
	changesAt: Date;
	/** The off-peak state after the change. */
	changesTo: boolean;
}

/**
 * Whether we are currently in the cheap window, and when that next flips.
 * Works even after 23:30, when the change (05:30) falls on the next day.
 */
export function getOffPeakStatus(instant: Date, timeZone: string = LONDON_TZ): OffPeakStatus {
	const offPeak = isOffPeakInstant(instant, timeZone);
	const [hour, minute, changesTo] = offPeak
		? [OFF_PEAK_END_MINUTES / 60, OFF_PEAK_END_MINUTES % 60, false]
		: [Math.floor(OFF_PEAK_START_MINUTES / 60), OFF_PEAK_START_MINUTES % 60, true];

	let at = zonedTimeOnDay(instant, hour, minute, 0, timeZone);
	if (at.getTime() <= instant.getTime()) {
		at = zonedTimeOnDay(instant, hour, minute, 1, timeZone);
	}

	return { offPeak, changesAt: at, changesTo };
}

/** Min and max unit rates across the day, rounded out to nice bounds. */
export function priceBounds(slots: readonly PriceSlot[]): { min: number; max: number } {
	const prices = slots.map((slot) => slot.priceIncVat);
	return {
		min: prices.length ? Math.min(...prices) : 0,
		max: prices.length ? Math.max(...prices) : 1
	};
}
